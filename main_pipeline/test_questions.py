def run_batch(chunks, index, embed_model, reranker, llm):
    """Пакетный прогон всех тестовых вопросов."""
    results_log = []
    for i, q in enumerate(QUESTIONS, 1):
        print("\n" + "=" * 70)
        print(f"[{i}/{len(QUESTIONS)}]  {q}")
        print("=" * 70)
        r = answer_one(q, chunks, index, embed_model, reranker, llm, bm25)
        results_log.append(r)

    BASE_DIR = Path(__file__).resolve().parent
    RESULTS_PATH = BASE_DIR.parent / "reports" / "test_results.json"
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        json.dump(results_log, f, ensure_ascii=False, indent=2)
    print(f"\nРезультаты сохранены в test_results.json")


def run_interactive(chunks, index, embed_model, reranker, llm):
    """Интерактивный режим: ввод вопросов вручную."""
    print("\n" + "=" * 70)
    print("ИНТЕРАКТИВНЫЙ РЕЖИМ")
    print("Введите вопрос или 'q' для выхода.")
    print("=" * 70)
    while True:
        try:
            query = input("\nВаш вопрос: ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nВыход.")
            break
        if query.lower() in ("q", "exit", "quit", ""):
            print("Выход.")
            break
        print("=" * 70)
        answer_one(query, chunks, index, embed_model, reranker, llm)


def run_single(question, chunks, index, embed_model, reranker, llm):
    """Один вопрос и выход."""
    print("=" * 70)
    print(f"{question}")
    print("=" * 70)
    answer_one(question, chunks, index, embed_model, reranker, llm)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--interactive", "-i", action="store_true",
                        help="Интерактивный режим")
    parser.add_argument("--question", "-q", type=str, default=None,
                        help="Задать один вопрос и выйти")
    args = parser.parse_args()

    chunks, index, embed_model, reranker, llm, bm25 = load_resources()

    if args.question:
        run_single(args.question, chunks, index, embed_model, reranker, llm)
    elif args.interactive:
        run_interactive(chunks, index, embed_model, reranker, llm)
    else:
        run_batch(chunks, index, embed_model, reranker, llm)